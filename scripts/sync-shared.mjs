// Copies the pure business logic into Edge Functions so client and server use identical maths.
// `node scripts/sync-shared.mjs --check` fails CI if the copy is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const src = fileURLToPath(new URL('../src/lib/calculations.ts', import.meta.url))
const dest = fileURLToPath(new URL('../supabase/functions/_shared/calculations.ts', import.meta.url))
const out = `// GENERATED by scripts/sync-shared.mjs from src/lib/calculations.ts. Do not edit.\n${readFileSync(src, 'utf8')}`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(dest, 'utf8') } catch { /* missing */ }
  if (current !== out) {
    console.error('supabase/functions/_shared/calculations.ts is stale. Run: npm run sync:shared')
    process.exit(1)
  }
  console.log('shared calculations in sync')
} else {
  writeFileSync(dest, out)
  console.log('synced', dest)
}
