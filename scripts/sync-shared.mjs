// Copies the pure business logic into the Edge Functions and the mobile app so the web client,
// the server and the app all use identical maths.
// `node scripts/sync-shared.mjs --check` fails CI if a copy is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const src = fileURLToPath(new URL('../src/lib/calculations.ts', import.meta.url))
const targets = ['../supabase/functions/_shared/calculations.ts', '../mobile/src/lib/calculations.ts'].map((p) => fileURLToPath(new URL(p, import.meta.url)))
const out = `// GENERATED by scripts/sync-shared.mjs from src/lib/calculations.ts. Do not edit.\n${readFileSync(src, 'utf8')}`

let stale = false
for (const dest of targets) {
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(dest, 'utf8') } catch { /* missing */ }
    if (current !== out) {
      console.error(`${dest} is stale. Run: npm run sync:shared`)
      stale = true
    }
  } else {
    writeFileSync(dest, out)
    console.log('synced', dest)
  }
}
if (stale) process.exit(1)
if (process.argv.includes('--check')) console.log('shared calculations in sync')
